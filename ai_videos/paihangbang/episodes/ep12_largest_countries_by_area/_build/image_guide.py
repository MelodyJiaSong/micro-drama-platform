def main() -> None:
    p = EP / "data.json"
    d = json.load(open(p, encoding="utf-8"))
    for it in d["items"]:
        looks, view, confuse, hint = GUIDE[it["country_iso2"]]
        it["image_hint"] = hint
        f = B / "content" / (Path(it["image"]).stem + ".md")
        body = f.read_text(encoding="utf-8") if f.exists() else f"# #{it['rank']} {it['name']} · photo subject: {it['subtitle']}\n"
        body = body.split("\n## 找图要点")[0].rstrip() + "\n"
        body += (f"\n## 找图要点（代理整理，据上文与调研）\n\n- 长相与辨认：{looks}\n- 经典视角 / 拍摄点：{view}\n"
                 f"- 易混对象（排除）：{confuse}\n- 写进 image_hint：{hint}\n")
        f.write_text(body, encoding="utf-8")
    p.write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("ok", len(d["items"]))


if __name__ == "__main__":
    main()

LIMITS = {"name": 22, "fact": 110}


def main():
    out = []
    problems = []
    for i, it in enumerate(ITEMS, 1):
        it = {"rank": i, **it}
        for k, lim in LIMITS.items():
            if len(it[k]) > lim:
                problems.append(f"#{i} {it['name']}: {k} {len(it[k])} > {lim}")
        out.append(it)
    if len(out) != 30:
        problems.append(f"count = {len(out)} (expected 30)")
    names = [o["name"] for o in out]
    if len(set(names)) != len(names):
        problems.append("duplicate names")
    path = pathlib.Path(__file__).with_name("items_draft.json")
    path.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {path} ({len(out)} items)")
    for o in out:
        print(f"{o['rank']:>2} {o['name']:<22} {o['country_iso2']} fact={len(o['fact'])}")
    if problems:
        print("PROBLEMS:")
        for p in problems:
            print("  " + p)
        raise SystemExit(1)


if __name__ == "__main__":
    main()

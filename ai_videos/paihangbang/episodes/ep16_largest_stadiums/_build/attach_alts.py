# -*- coding: utf-8 -*-
"""ep16：给风险图（licence unknown / FoP）配默认版替代图 image_alt（契约 v1.4）。
- 候选 id（cK）：从 _build/reselect/cand/<key>/ 复制、缩到长边 ≤ 2400 → assets/img/NN_<slug>_alt.jpg，账本照候选许可记；
- "gen"：用 assets/img/NN_<slug>_gen.png（tools/codex_image.py 生成，请求日志已自动记），账本 licence = "AI-generated (Codex image_gen)"。
    python _build/attach_alts.py"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from datetime import date
from pathlib import Path

from PIL import Image, ImageOps

B = Path(__file__).resolve().parent
EP = B.parent
sys.path.insert(0, str(B))
from image_reselect_ep16 import licence_url  # noqa: E402

ALTS = {0: "c12", 1: "c17", 2: "c4", 3: "c3", 5: "c32", 6: "c1", 7: "c4", 8: "c4", 9: "c3", 10: "c0", 11: "c19",
        13: "c0", 14: "c0", 17: "gen", 18: "c7", 19: "c0", 20: "c1", 25: "c4", 29: "c0", 30: "c2",
        31: "c13", 32: "c16", 34: "gen", 35: "c6", 37: "gen", 38: "gen", 39: "c0", 41: "gen", 42: "c7",
        43: "c2", 44: "gen", 45: "c0", 47: "c0", 48: "c9", 49: "c19"}
# QC 第 1 轮（M1）：AI 图每期 ≤ 3（只留 3 座 FoP 国的球迷示意图）；其余找不到可用替代的，默认版用诚实的无图卡
NOTES = {12: "Photo withheld: no freedom of panorama", 21: "Photo withheld: no freedom of panorama",
         27: "Photo withheld: no freedom of panorama"}
GEN_PROMPT_DIR = B / "gen"


def main() -> None:
    data = json.loads((EP / "data.json").read_text(encoding="utf-8"))
    assets = json.loads((EP / "assets.json").read_text(encoding="utf-8"))
    by_file = {a["file"]: a for a in assets}
    today = date.today().isoformat()
    for i, it in enumerate(data["items"]):
        cid = ALTS.get(i)
        if not cid or not it.get("image_risk"):            # 只有风险图才需要默认版替代
            it.pop("image_alt", None)
            it.pop("image_alt_credit", None)
            if i in NOTES and it.get("image_risk"):
                it["image_note"] = NOTES[i]
            continue
        stem = Path(it["image"]).stem                       # NN_slug
        if cid == "gen":
            rel = f"assets/img/{stem}_gen2.png" if (EP / f"assets/img/{stem}_gen2.png").exists() else f"assets/img/{stem}_gen.png"
            p = EP / rel
            if not p.exists():
                print("MISSING gen", rel)
                continue
            slug = stem.split('_', 1)[1]
            cands = sorted(GEN_PROMPT_DIR.glob(f"*{slug}_v2.txt")) if rel.endswith("_gen2.png") else sorted(GEN_PROMPT_DIR.glob(f"*{slug}.txt"))
            prompt = cands[0].read_text(encoding="utf-8").strip() if cands else ""
            entry = {"file": rel, "source_page": "", "source_url": "", "author": "AI-generated", "licence": "AI-generated (Codex image_gen)",
                     "licence_url": "", "attribution_required": False,
                     "modified": "generated by tools/codex_image.py (request logged in ai_videos/paihangbang/request_log.md); illustrative image, not a photo of the real stadium",
                     "sha256": hashlib.sha256(p.read_bytes()).hexdigest(), "retrieved_at": today, "fop_note": "", "prompt": prompt,
                     "selected_by": "follow-up 016/023 默认版替代：所在国无商用 FoP 或原图许可不明、全网无可商用替代"}
            credit = "AI-generated illustration (Codex)"
        else:
            key = f"{i:02d}_{stem}"
            d = B / "reselect" / "cand" / key
            m = next(x for x in json.loads((d / "meta.json").read_text(encoding="utf-8")) if x["id"] == cid)
            rel = f"assets/img/{stem}_alt.jpg"
            dst = EP / rel
            with Image.open(d / m["file"]) as im:
                im = ImageOps.exif_transpose(im).convert("RGB")
                if max(im.size) > 2400:
                    im.thumbnail((2400, 2400), Image.LANCZOS)
                im.save(dst, quality=90)
                size = im.size
            lic = m["licence"].strip()
            entry = {"file": rel, "source_page": m.get("page_url", ""), "source_url": m.get("image_url", ""), "author": m.get("author", ""),
                     "licence": lic, "licence_url": licence_url(lic),
                     "attribution_required": not re.match(r"(public domain|pd|cc0|pexels|unsplash|pixabay)", lic, re.I),
                     "modified": f"downscaled to {size[0]}x{size[1]} px and re-encoded as JPEG; renderer will crop",
                     "sha256": hashlib.sha256(dst.read_bytes()).hexdigest(), "retrieved_at": today, "fop_note": "",
                     "selected_by": f"默认版替代图（可商用；{m.get('source', '')}）"}
            credit = f"{m.get('author') or 'Unknown'} / {lic}"
        if rel in by_file:
            assets[assets.index(by_file[rel])] = entry
        else:
            assets.append(entry)
        it["image_alt"] = rel
        it["image_alt_credit"] = credit
    (EP / "data.json").write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (EP / "assets.json").write_text(json.dumps(assets, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("alts attached:", sum(1 for it in data["items"] if it.get("image_alt")))


if __name__ == "__main__":
    main()

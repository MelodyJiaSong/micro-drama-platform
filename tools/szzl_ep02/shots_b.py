def _swings(base: dict, times: tuple[float, ...], strike: str = "前劈R", w: float = 0.25, end: float | None = None) -> tuple:
    """平时 base 的拿法，每个命中时刻前后 w 秒切 strike（G5 命中贴身：挂死的兵器够不到目标）。
    end＝镜长：最后一下离镜尾不到 w 秒时把时段收在镜尾（build_previz 自检：末关键帧不得超出镜长）。"""
    cap = (lambda x: min(x, end)) if end is not None else (lambda x: x)
    out, t0 = [], 0.0
    for t in sorted(times):
        out += [dict(base, 起=t0, 止=t - w), dict(base, 姿=strike, 起=t - w, 止=cap(t + w))]
        t0 = cap(t + w)
    return tuple(out + ([dict(base, 起=t0)] if end is None or t0 < end else []))



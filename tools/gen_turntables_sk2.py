def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只跑闸门不写盘")
    args = ap.parse_args()
    out = sys.stdout.buffer
    errs: list[str] = []
    wrote = 0
    for key, c in CAST.items():
        f = CHARS / key / (key + ".md")
        if not f.exists():
            errs.append(f"{key} 卡不存在")
            continue
        sec, cn = section(key, c)
        if not (1000 <= cn <= 1950):
            errs.append(f"{key} turntable prompt {cn} 字，不在 1000–1950")
        if re.search(r"#[0-9A-Fa-f]{6}", sec):
            errs.append(f"{key} turntable 含 hex 色值")
        if args.check:
            out.write(f"· {key} {cn} 字\n".encode())
            continue
        s = io.open(f, encoding="utf-8").read()
        s = re.sub(r"\n---\n\n## turntable 说明.*?(?=\n## |\Z)", "\n", s, flags=re.S)
        s = re.sub(r"\n## turntable 说明.*?(?=\n## |\Z)", "\n", s, flags=re.S)
        s = s.rstrip() + "\n\n---\n\n" + sec
        io.open(f, "w", encoding="utf-8", newline="\n").write(s)
        out.write(f"OK {key} turntable {cn} 字\n".encode())
        wrote += 1
    if errs:
        out.write(f"\n闸门未过 {len(errs)} 条：\n".encode())
        for e in errs:
            out.write(("  x " + e + "\n").encode())
        raise SystemExit(1)
    out.write(f"\n合计 {wrote} 张卡已补 turntable\n".encode())


if __name__ == "__main__":
    main()

"""从共用 MCP 定义生成 Kimi / Codex 项目配置；不触碰用户配置。"""
from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SOURCE = ".agents/mcp.json"
TARGETS = (".kimi-code/mcp.json", ".codex/config.toml")


def render(root: Path) -> dict[str, str]:
    data = json.loads((root / SOURCE).read_text(encoding="utf-8-sig"))
    if not isinstance(data, dict) or set(data) != {"mcpServers"} or not isinstance(data["mcpServers"], dict):
        raise ValueError("共用 MCP 定义必须只有 mcpServers 对象")
    lines = ["# Generated by tools/sync_agent_config.py; edit .agents/mcp.json.", "", "[mcp_servers]", ""]
    for name, server in data["mcpServers"].items():
        if not isinstance(server, dict) or set(server) - {"command", "args", "env"}:
            raise ValueError(f"{name}: 仅支持已接入的 stdio command / args / env，未知字段不可静默丢弃")
        if not isinstance(server.get("command"), str) or not server["command"].strip():
            raise ValueError(f"{name}: command 必须为非空字符串")
        args, env = server.get("args", []), server.get("env", {})
        if not isinstance(args, list) or any(not isinstance(arg, str) for arg in args):
            raise ValueError(f"{name}: args 必须为字符串数组")
        if not isinstance(env, dict) or any(not isinstance(value, str) for value in env.values()):
            raise ValueError(f"{name}: env 必须为字符串映射")
        key = json.dumps(name, ensure_ascii=False)
        lines.extend([f"[mcp_servers.{key}]", f"command = {json.dumps(server['command'], ensure_ascii=False)}"])
        if "args" in server:
            lines.append(f"args = {json.dumps(args, ensure_ascii=False)}")
        if "env" in server:
            values = ", ".join(f"{json.dumps(k)} = {json.dumps(v, ensure_ascii=False)}" for k, v in env.items())
            lines.append(f"env = {{ {values} }}")
        lines.append("")
    codex = "\n".join(lines)
    if tomllib.loads(codex)["mcp_servers"] != data["mcpServers"]:
        raise ValueError("MCP 配置转换不一致")
    return {TARGETS[0]: json.dumps(data, ensure_ascii=False, indent=2) + "\n", TARGETS[1]: codex}


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--fix", action="store_true")
    args = parser.parse_args()
    try:
        outputs = render(REPO)
    except (OSError, ValueError) as exc:
        print(f"配置失败：{exc}")
        return 1
    drift = []
    for relative, expected in outputs.items():
        path = REPO / relative
        if path.is_file() and path.read_text(encoding="utf-8-sig") == expected:
            continue
        drift.append(relative)
        if args.fix:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    print("Kimi / Codex MCP 配置一致" if not drift else ("已同步：" if args.fix else "配置待同步：") + ", ".join(drift))
    return int(bool(drift) and not args.fix)


if __name__ == "__main__":
    raise SystemExit(main())

def swings(base: dict, times: tuple[float, ...], strike: str = "前劈R", w: float = 0.25) -> tuple:
    """平时 base 的拿法，每个命中时刻前后 w 秒切 strike（G5 命中贴身：挂死的兵器够不到目标）。"""
    out, t0 = [], 0.0
    for t in sorted(times):
        out += [dict(base, 起=t0, 止=t - w), dict(base, 姿=strike, 起=t - w, 止=t + w)]
        t0 = t + w
    return tuple(out + [dict(base, 起=t0)])

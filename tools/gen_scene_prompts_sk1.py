def han(text: str) -> int:
    return len([c for c in text if "一" <= c <= "鿿" or c in "，。；：、「」（）【】·？！——…"])


def sky_line(lk: Look) -> str:
    parts = [SKY[lk.tod].rstrip("。")]
    if WATER[lk.water]:
        parts.append(WATER[lk.water].rstrip("；"))
    if lk.aerial:
        parts.append("整幅像天气晴好时无人机航拍的实景（画面里看不到无人机、看不到飞行器的影子）")
    return "【天】" + "；".join(parts) + "。"


def light_line(lk: Look) -> str:
    parts = [lk.light.rstrip("；。"), f"{lk.ratio}，阴影里只有天光、没有补光"]
    if lk.dark:
        parts.append(f"{lk.dark}掉到近黑、不抬亮不补蓝")
    if lk.med:
        parts.append(lk.med)
    return "【光】" + "；".join(parts) + "。"


def wear_line(lk: Look) -> str:
    """每张图最多写三面 —— 再多就是堆字，会把注意力从最要紧的那几面上冲淡，也挤不进 2000 字。"""
    return "【质感与做旧】" + "".join(SURFACE[s] for s in lk.surf[:3])


def photo_line(lk: Look) -> str:
    return ("摄影: ARRI ALEXA，Super-35，Cooke S4/i %s，%s，1/48 秒；焦点在%s，%s；轻微暗角。"
            % (lk.foc, lk.stop, lk.focus, lk.dof))


def refs_line(lk: Look, key: str) -> tuple[str, str]:
    items = [] if lk.noref else [R_W] + list(lk.refs)
    # style_guide §10：上传位只给世界锚点 / 地点锚点 / **照片类**参考。判据看用途标签，
    # 不看 id —— 有些照片类参考正好也住在 `ref/` 里、沿用同一套 refNN 编号（如泰顺廊桥实拍）。
    for h, n in items:
        if "历史参考图" in n:
            raise SystemExit(f"{key}: `参考:` 里还挂着画类历史参考图 {h}（style_guide §10：宋画只作者对账，不上传）")
    if not items:
        return "参考: 无（纯文字自由生成，零参考图）", "参考用法: " + NOREF[lk.noref]
    ref = "参考: " + "、".join(f"`{h}({n})=>@`" for h, n in items)
    use = ["参考用法: 第一张是世界锚点，**只取影像基调**（光的性质、色、脏旧、颗粒、大气退远），构图与视角不取"]
    if len(items) > 1:
        use.append("；第二张是实拍照片，只定形制与真实材质光影，它的环境与天色不要")
    use.append("。槽位留空、上传时手填；构图与光以文字为准。")
    return ref, "".join(use)


def upload_line(key: str) -> str:
    """卡里「这一张要往上传窗口里放哪几张图」的那一行 —— 与 `参考:` 同一个出处，不手写。"""
    lk = LOOK[key]
    if lk.noref:
        return "**上传**：无（纯文字自由生成，零参考图）—— 见本视图 prompt 的 `参考用法:`"
    items = [R_W] + list(lk.refs)
    return ("**上传**：" + "、".join("`%s`（%s）" % (h, n) for h, n in items)
            + "。**宋画一律不上传**（style_guide §10）：它们仍在 `ref/` 里、仍是形制与验收的依据，"
              "但只由作者读完写进上面的文字，不进上传窗口。")


def negatives(lk: Look) -> str:
    out = [NEG_BASE, NEG_ARCH, NEG_CG]
    if lk.extra_neg:
        out.append(lk.extra_neg)
    return ", ".join(out)



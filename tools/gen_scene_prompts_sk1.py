OPTICS = re.compile(r"[；;，,]\s*(\d+(?:\.\d+)?)mm，f\d+(?:\.\d+)?，全景深，?")
FOCAL = re.compile(r"(\d+(?:\.\d+)?)\s*(?:mm|毫米|毫机等效)")


def set_line(lines: list[str], head: str, new: str) -> bool:
    for i, ln in enumerate(lines):
        if ln.startswith(head):
            lines[i] = new
            return True
    return False


def insert_before(lines: list[str], head: str, new: str) -> bool:
    for i, ln in enumerate(lines):
        if ln.startswith(head):
            lines.insert(i, new)
            return True
    return False


def restyle(key: str, body: str) -> str:
    lk = LOOK[key]
    lines = body.split("\n")

    # ① 机位：只摘掉光学尾巴（`28mm，f8，全景深`）——取景归作者，光学归本文件的 `摄影:` 行
    for idx, ln in enumerate(lines):
        if ln.startswith("机位:"):
            lines[idx] = OPTICS.sub("；", ln).replace("；；", "；")
            break

    # ② 参考 / 参考用法
    ref, use = refs_line(lk, key)
    # 对象族（p 卡 / bg17-2）的字段值整段包在反引号里。判据取**内容层**的 `主体:` / `形体规格:`，
    # 不取 `参考:` —— 后者是本文件自己重写的行，拿它当判据会让第二遍跑出不同结果。
    quoted = any(ln.startswith(("主体: `", "形体规格: `")) for ln in lines)
    set_line(lines, "参考:", ref)
    set_line(lines, "参考用法:", use)

    # ③ 摄影行（插在 机位: 之前；没有 机位: 就插在 场景: 之前；再没有就插在第 3 行）
    ph = photo_line(lk)
    if quoted:
        ph = "摄影: `" + ph[len("摄影: "):] + "`"
    lines = [ln for ln in lines if not ln.startswith("摄影:")]
    if not (insert_before(lines, "机位:", ph) or insert_before(lines, "场景:", ph)):
        lines.insert(min(3, len(lines)), ph)

    # ④ 天 / 光 / 做旧（三行都是「先整行删掉、再重新盖」，跑第二遍结果不变）
    wear = wear_line(lk)
    lines = [ln for ln in lines if not ln.startswith(("【质感与做旧】", "做旧:"))]
    li = light_line(lk)
    if any(ln.startswith("【天】") for ln in lines):
        set_line(lines, "【天】", sky_line(lk))
    if any(ln.startswith("【光】") for ln in lines):
        set_line(lines, "【光】", li)
    elif any(ln.startswith("光线:") for ln in lines):
        body = li[len("【光】"):]
        set_line(lines, "光线:", "光线: `" + body + "`" if quoted else "光线: " + body)
    elif not insert_before(lines, "负面词:", li):
        lines.append(li)
    # 做旧层：各卡原来的【年代感】讲的就是它，原地换掉（rule 4i ①：一个主体只留一处）
    field = "做旧: `" + wear[len("【质感与做旧】"):] + "`" if quoted else wear
    # 短路，不要写成 tuple —— tuple 的每一项都会先被求值，做旧层会被插好几处
    if not (set_line(lines, "【年代感】", wear)
            or insert_before(lines, "【天】", wear)
            or insert_before(lines, "姿态:", field)
            or insert_before(lines, "光线:", field)
            or insert_before(lines, "负面词:", wear)):
        lines.append(wear)

    # ⑤ 样式 / 渲染样式 / 光色
    if not set_line(lines, "样式:", "样式: " + STYLE_IMG):
        if quoted:
            set_line(lines, "渲染样式:", "渲染样式: `" + STYLE_IMG + "`")
        else:
            set_line(lines, "渲染样式:", "渲染样式: " + STYLE_IMG)
    # `光色:` 整行取消：它说的「与世界锚点同一套影调」`参考用法:` 已经说过一遍，
    # 两处各写一遍就是 rule 4i ① 说的副本；旧卡里残留的那一行在这里删掉。
    lines = [ln for ln in lines if not ln.startswith("光色:")]
    # ⑥ 立绘族把「风格:」整行换成样式串
    for i, ln in enumerate(lines):
        if ln.startswith(("风格:", "风格：")):
            lines[i] = "风格：" + STYLE_IMG
    # ⑦ inline 负面词
    for i, ln in enumerate(lines):
        if ln.startswith("负面词:"):
            lines[i] = "负面词: " + negatives(lk)
    return "\n".join(lines)


NEG_HEAD = re.compile(r"^## (?:反向提示词|负面词)（[^\n]*\n(.*?)(?=\n## |\n# |\Z)", re.S | re.M)


def restyle_file(path: Path, write: bool) -> list[str]:
    text = path.read_text(encoding="utf-8")
    done: list[str] = []
    extras: list[str] = []

    def repl(m: re.Match[str]) -> str:
        body = m.group(1)
        key = body.lstrip().split("\n")[0].split("_")[0]
        if key in SKIP or key not in LOOK:
            return m.group(0)
        done.append(key)
        if LOOK[key].extra_neg:
            extras.append(LOOK[key].extra_neg)
        return "```text\n" + restyle(key, body) + "\n```"

    text = re.sub(r"```text\n(.*?)\n```", repl, text, flags=re.S)
    if not done:
        return done

    # 「上传」行按视图顺序逐条换掉（它和 `参考:` 说的是同一件事，不能两处各写各的）
    order = iter(done)

    def uprepl(m: "re.Match[str]") -> str:
        k = next(order, None)
        return m.group(0) if k is None else upload_line(k)

    text = re.sub("^\\*\\*上传\\*\\*：[^\\n]*",
                  uprepl, text, flags=re.M)

    # 卡级负向块（`## 反向提示词…` / `## 负面词…` 一节里的最后一个围栏）：
    # 共用部分整体换新，卡自己追加的专属词原样留在后面（rule：可追加不可删）
    shared = ", ".join([NEG_BASE, NEG_ARCH, NEG_CG] + sorted(set(extras)))
    base = {w.strip() for s in (NEG_BASE, NEG_ARCH, NEG_CG, *extras) for w in s.split(",") if w.strip()}

    def negrepl(m: re.Match[str]) -> str:
        sec = m.group(0)
        fences = re.findall(r"```text\n(.*?)\n```", sec, re.S)
        if not fences:
            return sec
        own = [w.strip() for w in fences[-1].replace("\n", " ").split(",")
               if w.strip() and w.strip() not in base]
        new = shared + (", " + ", ".join(own) if own else "")
        return sec.replace("```text\n" + fences[-1] + "\n```", "```text\n" + new + "\n```")

    text = re.sub(r"^## (?:反向提示词|负面词)（[\s\S]*?(?=\n## |\n# |\Z)", negrepl, text, flags=re.M)

    def countrepl(m: re.Match[str]) -> str:
        body = m.group(1).split("\n", 1)[1].rsplit("\n```", 1)[0]
        return (m.group(1) + m.group(2)
                + f"**字数**：{han(body)} 中文字符"
                  "（由 `tools/gen_scene_prompts_sk1.py` 盖章后重算）")

    text = re.sub(r"(```text\n(?:bg|p|c)\d+-\d+_(?:(?!```)[\s\S])*?\n```)"
                  r"((?:(?!```)[\s\S]){0,240}?)\*\*字数\*\*：[^\n]*",
                  countrepl, text)
    if write:
        path.write_text(text, encoding="utf-8")
    return done


def gate() -> None:
    sg = STYLE_GUIDE.read_text(encoding="utf-8")
    fences = re.findall(r"^```\n(.*?)\n```", sg, flags=re.S | re.M)
    for name, text in (("STYLE_BASE", STYLE_BASE), ("NEG_BASE", NEG_BASE),
                       ("NEG_ARCH", NEG_ARCH), ("NEG_CG", NEG_CG)):
        if text not in fences:
            raise SystemExit(f"{name} ≠ style_guide.md 围栏块（rule 4i ①：改串要两边一起改）")


PROMPT_RE = "```text" + chr(10) + "((?:bg|p|c)[0-9]+-[0-9]+_(?s:.)*?)" + chr(10) + "```"
# style_guide.md §7 长度自检：**图 prompt 硬线 < 2000 字**（用户 2026-09-16 定调）。
# 下限 1200 而不是 1500：室内与夜场镜画面里本来就没那么多东西，硬凑字只会稀释重点。
# 超上限一律 raise —— 挤不进去时砍的是**共用串与重复**，不是砍画面信息（rule 4i ①）。
LO, HI = 1200, 1999


def measure() -> dict[str, int]:
    """逐块量字数：只量图 prompt 块本身，量中文字符 + 中文标点（与 §7 口径一致）。"""
    out: dict[str, int] = {}
    for md in sorted(A.rglob("*.md")):
        for m in re.finditer(PROMPT_RE, md.read_text(encoding="utf-8")):
            key = m.group(1).split("_")[0]
            if key in LOOK:
                out[key] = han(m.group(1))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    gate()
    total: list[str] = []
    for md in sorted(A.rglob("*.md")):
        if md.name in ("style_guide.md", "look_research.md", "qc_stage2.md"):
            continue
        total += restyle_file(md, write=not args.check)
    missing = sorted(set(LOOK) - set(total))
    print(f"盖章 {len(total)} 个 prompt：{', '.join(sorted(total))}")
    if missing:
        raise SystemExit(f"LOOK 表里有 {len(missing)} 个键没落到任何卡上：{missing}")
    n_by_key = measure()
    over = [f"{k} {n} 字" for k, n in sorted(n_by_key.items()) if n > HI]
    thin = [f"{k} {n} 字" for k, n in sorted(n_by_key.items()) if n < LO]
    if over:      # 上限是用户定的硬线，越界一律 raise
        raise SystemExit(f"图 prompt 超 {HI} 字（硬线 < 2000）：" + "、".join(over))
    if thin:      # 下限只是「别写太空」的提醒：室内与夜场镜本来就没那么多东西
        print("· 偏短（提醒，不拦）：" + "、".join(thin))
    print(f"· 字数 {min(n_by_key.values())}–{max(n_by_key.values())}（硬线 < {HI + 1}）")
    print("OK（--check 模式未写盘）" if args.check else "OK（已写盘）")


if __name__ == "__main__":
    main()

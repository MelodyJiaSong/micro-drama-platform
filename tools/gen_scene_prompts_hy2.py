    for v in sub["views"]:
        kind = v["kind"]
        base = BASE_ACC_NIGHT if night else BASE_ACC_DAY
        acc = NL.join("- [ ] " + a for a in (v.get("extra_acc", []) + base))
        if sub["anchor"] and v["vid"] == 1:
            upload = "无——本图不挂任何参考图"
            ref_line = "参考: 无 —— 本图是全片的视觉源头，不挂任何参考图"
        elif kind in ("chain", "place", "wide"):
            upload = sub["ref"]
            ref_line = "参考: `" + sub["ref"] + "=>@`"
        else:
            upload = dirname + "/" + key + "-1.png(长相标准)"
            ref_line = "参考: `" + dirname + "/" + key + "-1.png(长相标准)=>@`"

        use = ("" if not v.get("use") else NL + "**用在**：" + v["use"] + NL)
        out.append(VIEW_HEAD.format(vid=v["vid"], name=v["name"], blurb=BLURB[kind],
                                    use=use, acc=acc, upload=upload, dirname=dirname, key=key))

        p = [key + "-" + str(v["vid"]) + "_" + v["name"], ref_line,
             "参考用法: " + USAGE[kind]]
        if v["vid"] == 1 and (sub["anchor"] or kind in ("chain", "place", "wide")):
            p.append("场景: " + sub["scene"])
            if sub["const"]:
                p.append("恒定: " + sub["const"])
        else:
            p.append("恒定: 与本主体锚点图同一材质、色板、光线状态、湿度与雾的密度；同一做旧与使用程度。")
        p.append("机位: " + v["cam"])
        if v.get("light"):
            p.append("光色: " + v["light"])
        p.append("构图: " + (COMP_NIGHT if night else COMP_DAY))
        p.append("样式: " + STYLE)
        out.append(NL + FENCE + "text" + NL + NL.join(p) + NL + FENCE + NL)

    out.append(NL + "---" + NL + NL +
               "## 反向提示词（本主体全部视图共用）" + NL + NL +
               "粘进平台的「反向提示词 / negative」输入框，**不要并进正向 prompt**。" + NL + NL +
               FENCE + "text" + NL + (NEG_NIGHT if night else NEG_DAY) + NL + FENCE + NL)

    path = os.path.join(d, dirname + ".md")
    io.open(path, "w", encoding="utf-8", newline=NL).write("".join(out))
    return path



def ref_cell(sub, v):
    if sub["anchor"] and v["vid"] == 1:
        return "**无（自由生成）**"
    if v["kind"] in ("chain", "place"):
        return "`" + sub["ref"] + "=>@`"
    return "`" + sub["dirname"] + "/" + sub["key"] + "-1.png(长相标准)=>@`"


def emit(sub):
    key, dirname = sub["key"], sub["dirname"]
    d = os.path.join(ROOT, dirname)
    os.makedirs(d, exist_ok=True)
    night = sub["night"]

    rows = ["| {} | `{}` | {} | {} |".format(
        v["vid"], v["name"], ref_cell(sub, v), "★ 必做" if v.get("must", True) else "按需")
        for v in sub["views"]]

    out = [HEAD.format(title=sub["title"], place=sub["place"], state=sub["state"],
                       dirname=dirname, key=key, fence=FENCE, world_desc=WORLD_DESC,
                       role=sub["role"], blocked=sub["blocked"],
                       order_rows=NL.join(rows))]

    for v in sub["views"]:
        kind = v["kind"]
        base = BASE_ACC_NIGHT if night else BASE_ACC_DAY
        acc = NL.join("- [ ] " + a for a in (v.get("extra_acc", []) + base))
        if sub["anchor"] and v["vid"] == 1:
            upload = "无——本图不挂任何参考图"
            ref_line = "参考: 无 —— 本图是全片的视觉源头，不挂任何参考图"
        elif kind in ("chain", "place"):
            upload = sub["ref"]
            ref_line = "参考: `" + sub["ref"] + "=>@`"
        else:
            upload = dirname + "/" + key + "-1.png(长相标准)"
            ref_line = "参考: `" + dirname + "/" + key + "-1.png(长相标准)=>@`"

        use = ("" if not v.get("use") else NL + "**用在**：" + v["use"] + NL)
        out.append(VIEW_HEAD.format(vid=v["vid"], name=v["name"],
                                    badge="★ 必做" if v.get("must", True) else "（按需）",
                                    blurb=BLURB[kind], use=use, acc=acc, upload=upload,
                                    dirname=dirname, key=key))

        p = [key + "-" + str(v["vid"]) + "_" + v["name"], ref_line,
             "参考用法: " + USAGE[kind]]
        if v["vid"] == 1 and (sub["anchor"] or kind in ("chain", "place")):
            p.append("场景: " + sub["scene"])
            if sub["const"]:
                p.append("恒定: " + sub["const"])
        else:
            p.append("恒定: 与本主体锚点图同一材质、色板、光线状态、湿度与雾的密度；同一做旧与使用程度。")
        p.append("机位: " + v["cam"])

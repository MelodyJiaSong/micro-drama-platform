def gate(cards: dict[Path, str]) -> list[str]:
    bad: list[str] = []
    for path, text in cards.items():
        if HEX_RE.search(text):
            bad.append("%s: 出现 hex 颜色（rule 1b 零 hex）" % path.name)
        for m in SLOT_RE.finditer(text):
            bad.append("%s: `=>@` 后不得代填槽位号 —— %r" % (path.name, m.group(0)))
    for s in SCENES:
        if not s.not_x.strip():
            bad.append("%s: 锁定串缺「不是 X」（rule 12.8）" % s.key)
        if not s.reverse.strip():
            bad.append("%s: 缺反向声明（16.9 / K32）" % s.key)
        body = s.body + s.fields[0][1]
        if "#" in body:
            bad.append("%s: prompt 正文里有 #" % s.key)
    keys = [s.key for s in SCENES]
    if len(set(keys)) != len(keys):
        bad.append("场景键重复：%s" % keys)
    # 共用串污染：交给全仓唯一实现判（K32 C1）。新站不给 legacy 豁免——一条都没有。
    # 用 check_drama 而不是 gate()：gate() 自己 raise，这里要把它的结论并进同一份报告。
    by_asset = {p.stem: t for p, t in cards.items()}
    for i in prompt_light.check_drama(by_asset):
        if i.level == "blocker":
            bad.append("%s [%s] %s" % (i.shot, i.code, i.detail))
        else:
            print("warning %s [%s] %s" % (i.shot, i.code, i.detail))
    return bad


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验、不写盘")
    args = ap.parse_args()

    neg, style = load_shared()
    cards: dict[Path, str] = {}
    for s in SCENES:
        d = SCENE_ROOT / ("%s_%s" % (s.key, s.name))
        cards[d / ("%s_%s.md" % (s.key, s.name))] = scene_card(s, neg, style)
    for d in load_toml("props.toml"):
        p = PROP_ROOT / ("%s_%s" % (d["key"], d["name"]))
        cards[p / ("%s_%s.md" % (d["key"], d["name"]))] = prop_card(d, neg, style)
    for d in load_toml("characters.toml"):
        p = CHAR_ROOT / ("%s_%s" % (d["key"], d["name"]))
        cards[p / ("%s_%s.md" % (d["key"], d["name"]))] = char_card(d, neg, style)

    problems = gate(cards)
    if problems:
        for p in problems:
            print("BLOCKER", p)
        return 1

    if args.check:
        drift = [p.name for p, t in cards.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != t]
        if drift:
            print("DRIFT（卡被手改过或生成器已变）：", ", ".join(drift))
            return 1
        print("check ok — %d 张场景卡与生成器一致" % len(cards))
        return 0

    for path, text in cards.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        (path.parent / "ref").mkdir(exist_ok=True)
        path.write_text(text, encoding="utf-8", newline=NL)
        print("wrote", path.relative_to(REPO))
    print("%d 张场景卡；共用串与 style_guide.md 逐字一致" % len(cards))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

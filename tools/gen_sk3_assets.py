def load_toml(name: str) -> list[dict]:
    p = DATA / name
    if not p.exists():
        return []
    import tomllib
    body = tomllib.loads(p.read_text(encoding="utf-8"))
    return body.get(p.stem.rstrip("s") if p.stem.endswith("s") else p.stem, [])



def _fences(path: Path) -> list[str]:
    body = path.read_text(encoding="utf-8")
    return re.findall(r"```text\n(.*?)\n```", body, flags=re.S)


def load_shared() -> tuple[str, str]:
    f = _fences(STYLE_GUIDE)
    neg = next((x for x in f if "thatched roof" in x), None)
    style = next((x for x in f if "写实纪录片影像" in x), None)
    if neg is None or style is None:
        raise SystemExit("style_guide.md 缺负向块或 STYLE_BASE 围栏")
    return neg.strip(), style.strip()



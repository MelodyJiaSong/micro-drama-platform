# （情绪最高点 / 签名定帧）排在各自镜的**片尾**，坏了只重跑那一条、前面的段还能单独取用。
MIN_D, MAX_D = 15, 30


def tc(sec):
    return "%02d:%02d" % (sec // 60, sec % 60)


MEDIA_EXT = (".mp4", ".png", ".jpg", ".jpeg", ".mov", ".wav", ".mp3")


def prune_stale_shot_dirs(keep):
    """删掉镜数缩减后多出来的 shot 目录 —— 但**只删纯 md 目录**。

    2026-09-07 教训：合并镜次时用 `rm -rf shots/` 整树重建，把 16 个已渲染的
    shot mp4 一起删了（渲染稿与 md 同目录，且当时还没 push 进 R2，不可恢复）。
    md 是可重生成的，渲染稿不是 —— 生成器覆写 md 即可，永远不要整树删除。
    带媒体的多余目录只报警不删，由人处理。
    """
    shots_dir = os.path.join(ROOT, "shots")
    if not os.path.isdir(shots_dir):
        return
    for name in sorted(os.listdir(shots_dir)):
        if not (name.startswith("shot") and name[4:].isdigit()):
            continue
        if int(name[4:]) <= keep:
            continue
        d = os.path.join(shots_dir, name)
        media = [os.path.join(r, f) for r, _, fs in os.walk(d)
                 for f in fs if f.lower().endswith(MEDIA_EXT)]
        if media:
            print("！保留 %s —— 内含 %d 个媒体文件，请人工确认后再删：" % (name, len(media)))
            for m in media:
                print("    " + m)
            continue
        for r, dirs, fs in os.walk(d, topdown=False):
            for f in fs:
                os.remove(os.path.join(r, f))
            for x in dirs:
                os.rmdir(os.path.join(r, x))
        os.rmdir(d)
        print("已删除多余的空镜目录 " + name)



    """(负面词行之前含「负面词：」, 负面词行, 其后)——卡里只有立绘块这一行「负面词：」。"""
    head, sep, rest = text.partition("负面词：")
    line, nl, after = rest.partition("\n")
    return head + sep, line, nl + after



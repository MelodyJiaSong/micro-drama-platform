"""Generate/check Claude adapters over canonical .agents skills; never copy bodies."""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
ALIASES = REPO / ".agents" / "skill-aliases.json"
SOURCES = REPO / ".agents" / "skills"
ENTRIES = REPO / ".claude" / "skills"
MARKER = "<!-- Generated by tools/sync_agent_skills.py; edit the source skill. -->"


def load_aliases() -> dict[str, str]:
    def unique_pairs(pairs: list[tuple[str, str]]) -> dict[str, str]:
        result: dict[str, str] = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"duplicate alias: {key}")
            result[key] = value
        return result

    aliases = json.loads(ALIASES.read_text(encoding="utf-8"), object_pairs_hook=unique_pairs)
    if not isinstance(aliases, dict) or not aliases:
        raise ValueError("aliases must be a nonempty object")
    for alias, legacy in aliases.items():
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", alias) or len(alias) > 64:
            raise ValueError(f"invalid alias: {alias}")
        if not isinstance(legacy, str) or not legacy or not re.fullmatch(r"[\w-]+", legacy):
            raise ValueError(f"invalid legacy command for {alias}")
        if legacy in aliases and legacy != alias:
            raise ValueError(f"legacy command collides with another canonical skill: {legacy}")
    sources = {p.parent.name for p in SOURCES.glob("*/SKILL.md")}
    if len(set(aliases.values())) != len(aliases) or set(aliases) != sources:
        raise ValueError("aliases must cover every canonical skill exactly once")
    return aliases


def render(command: str, alias: str) -> str:
    path = SOURCES / alias / "SKILL.md"
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\r?\n(.*?)\r?\n---(?:\r?\n|$)", text, re.S)
    if match is None:
        raise ValueError(f"missing frontmatter: {alias}")
    meta = yaml.safe_load(match[1])
    if not isinstance(meta, dict) or meta.get("name") != alias or MARKER in text:
        raise ValueError(f"canonical skill must own its body and match its directory: {alias}")
    desc = meta.get("description")
    if not isinstance(desc, str) or not desc.strip() or len(desc) > 500 or "\n" in desc:
        raise ValueError(f"description must be one line, 1..500 characters: {alias}")
    rel = path.relative_to(REPO).as_posix()
    hint = meta.get("metadata", {}).get("claude", {}).get("argument-hint")
    if hint is not None and not isinstance(hint, str):
        raise ValueError(f"argument-hint must be a string: {alias}")
    hint_line = f"argument-hint: {json.dumps(hint, ensure_ascii=False)}\n" if hint else ""
    arguments = "\n本次用户参数：$ARGUMENTS。按源 skill 解析，不把占位符当字面值执行。\n"
    return (
        f"---\nname: {command}\ndescription: {json.dumps(desc, ensure_ascii=False)}\n{hint_line}---\n\n"
        f"{MARKER}\n\n"
        f"# {command}\n\n"
        f"先读取仓库根目录的 [AGENTS.md](../../../AGENTS.md)，按任务路由读取共用约定。\n"
        f"然后读取并执行完整的 [源 skill](../../../{rel})（`{alias}`）；本入口不包含工作流正文。\n\n"
        f"源路径相对仓库根：`{rel}`。其中「同目录」、playbooks、references 等相对路径以源文件目录为基准。\n"
        "工具、提问、独立审稿、参数与收尾按 `CONVENTIONS.md` 的 Tool scoping and team coordination 映射；"
        "从实际用户消息读取参数。缺少必需能力时记录未审 / blocker，不能宣称 QC 通过。\n"
        f"{arguments}"
    )


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="read-only drift and metadata check")
    args = ap.parse_args()
    aliases = load_aliases()
    expected = {
        ENTRIES / command / "SKILL.md": render(command, alias)
        for alias, legacy in aliases.items()
        for command in dict.fromkeys((alias, legacy))
    }
    problems: list[str] = []
    pending: list[tuple[Path, str]] = []
    for path, content in expected.items():
        existing = path.read_text(encoding="utf-8") if path.is_file() else None
        if existing == content:
            continue
        if existing is not None and MARKER not in existing:
            problems.append(f"refusing to overwrite non-generated entry: {path.relative_to(REPO)}")
        elif args.check:
            problems.append(f"missing or stale entry: {path.relative_to(REPO)}")
        else:
            pending.append((path, content))
    for path in ENTRIES.glob("*/SKILL.md"):
        if path not in expected:
            reason = "obsolete generated entry (review before removal)" if MARKER in path.read_text(encoding="utf-8") else "unmapped Claude skill (maintain its body under .agents/skills)"
            problems.append(f"{reason}: {path.relative_to(REPO)}")
    for problem in problems:
        print(problem)
    if problems:
        return 1
    for path, content in pending:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    print(f"{len(aliases)} canonical skills / {len(expected)} Claude adapters {'checked' if args.check else 'synced'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

def _read(path: str) -> str:
    return io.open(path, encoding="utf-8").read()


def lock_fences(path: str) -> list[str]:
    m = re.search(r"^## 锁定描述符[^\n]*\n(.*?)(?=^## )", _read(path), flags=re.S | re.M)
    return re.findall(r"^```\n(.*?)\n```", m.group(1), flags=re.S | re.M) if m else []


def pick(fences: list[str], head: str) -> str:
    got = [f for f in fences if f.startswith(head)]
    if len(got) != 1:
        raise SystemExit("卡里找不到唯一以「%s」开头的锁定串" % head)
    return got[0]


